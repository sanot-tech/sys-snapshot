/// 📸 Основная работа: снять снимок, спрятав откат в мягких ссылках.
fn take_snapshot() -> i32 {
    let root = snapshot_root();

    // 🚦 Проверка места ДО работы. Снимок, который забьёт диск, опаснее
    //    отсутствия снимка.
    let free = free_mb(SNAPSHOT_ROOT);
    if free != 0 && free < MIN_FREE_MB {
        err(&format!(
            "свободно {free} МБ, нужно минимум {MIN_FREE_MB} МБ — снимок пропущен"
        ));
        return 1;
    }
    if free != 0 {
        step("🚦", &format!("свободно {free} МБ — места достаточно"));
    }

    // 📂 Каталог для снимка. Создаём заранее, чтобы rsync мог в него писать.
    let id = snapshot_id();
    let dest = root.join(&id);
    if let Err(e) = fs::create_dir_all(&dest) {
        err(&format!("создать {}: {e}", dest.display()));
        return 1;
    }
    step("📸", &format!("снимок {id} → {}", dest.display()));

    // 🛡️ РЕАЛЬНАЯ ЗАЩИТА ОТ РЕКУРСИИ — утверждение, а не предупреждение.
    //
    // 📗 Предыдущая версия этого кода печатала «источник содержит хранилище —
    //    пропускаю» и тут же всё равно копировала этот источник. То есть
    //    сообщение врало: обещанного пропуска не было. Хуже того, оно
    //    приучило бы читателя верить в проверку, которой не существует.
    //
    //    Что здесь по-настоящему: единственная защита от рекурсии —
    //    паттерн `.snapshots/` в EXCLUDES. Если его оттуда убрать, снимок
    //    начнёт копировать сам себя и через несколько часов забьёт диск.
    //    Поэтому проверяем не источники, а НАЛИЧИЕ паттерна, и падаем,
    //    если защиты нет. Проверка после копирования тут бесполезна.
    if !EXCLUDES.contains(&".snapshots/") {
        err("в EXCLUDES нет \".snapshots/\" — снимок скопирует сам себя в себя");
        err("верни паттерн и только потом запускай. Снимок не снят.");
        return 1;
    }
    // 📗 Проверяем и то, что хранилище действительно внутри снимаемого
    //    дерева: именно в этом случае исключение обязано быть.
    if WATCH.iter().any(|(_, src)| SNAPSHOT_ROOT.starts_with(&format!("{src}/"))) {
        step("🛡️", "хранилище внутри снимаемого дерева — защита паттерном «.snapshots/» активна");
    }

    // 🔗 Ищем предыдущий снимок: rsync через --link-dest будет переиспользовать
    //    неизменившиеся файлы из него как жёсткие ссылки. Это и делает
    //    снимок инкрементальным: платим только за разницу.
    let existing = list_snapshots();
    let prev = existing.iter().rev().find(|(n, _)| *n != id).map(|(_, p)| p.clone());

    match &prev {
        Some(p) => step("🔗", &format!("база для ссылок: {}", p.display())),
        None => step("🔗", "базового снимка нет — будет полная копия"),
    }

    // 📡 Копируем каждый отслеживаемый путь.
    let mut failed = false;
    for (name, source) in WATCH {
        if !Path::new(source).exists() {
            step("⏭️", &format!("{name}: {source} не существует — пропускаю"));
            continue;
        }

        let target = dest.join(name);

        // 🛡️ ТРЕБОВАНИЕ «НЕ НАГРУЖАТЬ СИСТЕМУ» — реализуемо здесь, а не
        //    только в комментарии: rsync запускается не сам по себе, а через
        //    обёртки nice и ionice.
        //    nice -n 19 → самый низкий приоритет CPU (никто не заметит)
        //    ionice -c3 → idle-класс: диск трогаем только когда он простаивает
        //    Без этого часовой снимок заметно дёргал бы ноутбук.
        let mut cmd = Command::new("nice");

        cmd.arg("-n").arg("19");      // 📗 максимальная «вежливость» CPU
        cmd.arg("ionice").arg("-c").arg("3");  // 📗 idle-класс ввода-вывода
        cmd.arg("rsync");

        // 📗 -a: права, времена, ссылки, устройства.
        cmd.arg("-a");

        // 🔐 --fake-super: КЛЮЧЕВАЯ ОПЦИЯ, из-за неё инструмент вообще
        //    работает без root.
        //    Проблема была такая: с обычным -a rsync сохраняет владельца
        //    файла, и root-файлы из /etc попадали в снимок с владельцем root.
        //    Дальше пользователь без sudo НЕ МОГ удалить свой же снимок —
        //    «Отказано в доступе» на каждом файле.
        //    --fake-super кладёт привилегированные атрибуты (uid/gid) в
        //    расширенные атрибуты файла, а на диске файл принадлежит
        //    текущему пользователю. Снимок можно свободно удалять, а при
        //    откате с правами root владельца восстановит сам rsync.
        cmd.arg("--fake-super");
        // 📗 --delete — снимок это точная копия, а не накопитель мусора:
        //        удалённый в оригинале файл должен исчезнуть и в снимке.
        cmd.arg("--delete");
        // 📗 --info=STATS2 — краткая статистика в конце, не построчно.
        cmd.arg("--info=STATS2");

        // 🔗 Ключевая опция: жёсткие ссылки на неизменившееся. Именно она
        //    превращает 24 полных копии в 24 дельты.
        if let Some(p) = &prev {
            cmd.arg(format!("--link-dest={}", p.join(name).display()));
        }

        // 🚫 Исключения: кэши и пересобираемые деревья не копируем.
        for ex in EXCLUDES {
            cmd.arg(format!("--exclude={ex}"));
        }

        // 📉 Потолок 20 МБ/с: достаточно для фоновой задачи, не душит сеть.
        cmd.arg("--bwlimit=20000");

        cmd.arg(format!("{source}/"));
        cmd.arg(&target);

        // 📗 stdout уводим в null, stderr наследуем — видим ошибки rsync.
        let out = cmd
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::inherit())
            .output();

        match out {
            Ok(o) if o.status.success() => ok(&format!("{name}: снято")),

            // 📗 Код 23 (и 24) у rsync означает «часть файлов не перенеслась».
            //    Для нас это НОРМАЛЬНО: часть /etc физически нечитаема без
            //    root (ssl/private, shadow, sudoers.d). Снимок при этом
            //    пригоден — в нём всё, что пользователю положено читать.
            //    Ставить failed=true здесь значило бы, что снимок вечно
            //    числился бы «битым» из-за прав доступа, которые у нас
            //    и не должны быть.
            //    Поэтому: предупреждаем, но снимок засчитываем.
            Ok(o) if o.status.code() == Some(23) || o.status.code() == Some(24) => {
                step(
                    "⚠️",
                    &format!("{name}: снято частично (код {}) — часть /etc не читается без root",
                             o.status.code().unwrap_or(0)),
                );
            }

            Ok(o) => {
                // 📌 Любой другой код — уже настоящая ошибка, а не права доступа.
                err(&format!("{name}: rsync завершился с {}", o.status));
                failed = true;
            }
            Err(e) => {
                err(&format!("{name}: не запустился — {e}"));
                failed = true;
            }
        }
    }

    if failed {
        err("снимок снят частично — откат на него может быть неполным");
        return 1;
    }

    // 🧹 Удаляем снимки старше KEEP_SNAPSHOTS.
    prune_old_snapshots();

    // 📊 ЧЕСТНЫЙ отчёт о месте.
    //
    // 📗 Почему не `du -sm <один снимок>`: du не дедуплицирует жёсткие
    //    ссылки между своим аргументом, поэтому он покажет ПОЛНЫЙ размер
    //    снимка (607 МБ), хотя реально этот снимок добавил на диск пару
    //    мегабайт. Это выглядит как «снимок весит 607 МБ» и вводит в
    //    заблуждение ровно в том месте, где важна правда.
    //
    //    Правильная метрика — `du -smc ~/.snapshots`: du видит ВСЕ снимки
    //    разом и считает каждый inode один раз. Это и есть реальная стоимость.
    let total = Command::new("du")
        .arg("-smc")
        .arg(SNAPSHOT_ROOT)
        .output()
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .and_then(|t| {
            t.lines()
                .next_back()
                .and_then(|l| l.split_whitespace().next())
                .map(|s| s.to_string())
        })
        .unwrap_or_else(|| "?".into());

    let count = list_snapshots().len();
    step(
        "📊",
        &format!("хранилище всего: {total} МБ на {count} снимк. — это сумма с учётом общих файлов"),
    );
    info("   (неизменённые файлы хранятся ОДИН раз и ссылаются на себя из всех снимков)");

    ok(&format!("снимок {id} готов"));
    0
}

/// 🧹 Оставить только последние KEEP_SNAPSHOTS снимков.
fn prune_old_snapshots() {
    let all = list_snapshots();
    if all.len() <= KEEP_SNAPSHOTS {
        return;
    }

    // 📌 Удаляем всё до границы: снимки отсортированы по времени.
    let to_drop = all.len() - KEEP_SNAPSHOTS;
    for (name, path) in all.iter().take(to_drop) {
        // 📗 chmod -R u+w перед удалением: снимок может содержать файлы
        //    с закрытыми правами (например /etc/shadow с режимом 000 или
        //    read-only каталоги). remove_dir_all на них споткнётся.
        //    chmod меняет только биты записи владельца — ничего лишнего.
        let _ = Command::new("chmod")
            .arg("-R").arg("u+w")
            .arg(path)
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status();

        match fs::remove_dir_all(path) {
            Ok(()) => step("🧹", &format!("удалён старый снимок {name}")),
            Err(e) => err(&format!("удалить {}: {e}", path.display())),
        }
    }
}

