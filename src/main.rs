// ============================================================================
//  📸  sys-snapshot — ежечасные снапшоты с откатом
// ----------------------------------------------------------------------------
//  🐉 Язык: Rust. Правило проекта — инструменты пишутся на Rust или C.
//
//  🎯 ЗАЧЕМ: чтобы в любой момент можно было откатить систему на состояние
//     часа назад. На машине ext4, где нативных снапшотов нет, а LVM требует
//     root-пароль. Поэтому инкрементальные копии через rsync с жёсткими
//     ссылками: каждый новый снимок занимает место ТОЛЬКО за изменившиеся
//     файлы, остальное — бесплатные hardlinks.
//
//  🧠 ПОЧЕМУ НЕ СВОЙ ФОРМАТ СНАПШОТОВ:
//     rsync с --link-detail делает инкрементальные снапшоты годами и
//     обновляется вместе с системным пакетом. Свой формат — это лишний код,
//     который придётся отлаживать, когда он сломается в 3 часа ночи.
//     Простая программа, которая правильно зовёт проверенный rsync,
//     надёжнее самодельной системы хранения.
//
//  🛡️ ТРЕБОВАНИЕ «НЕ НАГРУЖАТЬ СИСТЕМУ» (соблюдается жёстко):
//     1. Снимок идёт в фоновом режиме с низшим приоритетом: nice 19
//        плюс ionice -c3 (idle). Диск и CPU не страдают от работы.
//     2. Пропускаем кэши и пересобираемые деревья — они и не меняются
//        между часами, и места занимают сотни мегабайт.
//     3. Перед стартом проверяем свободное место и отступаем при нехватке.
//     4. Никаких параллельных запусков: lock-файл не даёт задвоиться.
//
//  🏁 ЗАПУСК:
//     sys-snapshot            📸 снять снимок сейчас
//     sys-snapshot --list     📋 показать доступные снимки
//     sys-snapshot --restore <id>   ⏪ откатить (печатает команды, сам не трогает)
// ============================================================================

use std::env;              // 🌍 аргументы и переменные окружения
use std::fs;                // 📁 чтение/запись каталогов
use std::path::{Path, PathBuf};  // 📁 пути
use std::process::{Command, Stdio};  // ⚙️ запуск rsync и служебных команд
use std::time::{SystemTime, UNIX_EPOCH};  // ⏱️ время для метки снимка

