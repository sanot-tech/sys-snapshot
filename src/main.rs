/// 📍 Где лежат снимки. На том же разделе, что и оригиналы, — иначе
///    жёсткие ссылки невозможны и каждый снимок съедает полную копию.
const SNAPSHOT_ROOT: &str = "/home/pcadm/.snapshots";

/// 📂 Что снимаем. Только то, что реально меняется между часами.
///    Обоснование каждого пути — в комментарии, иначе через полгода
///    никто не вспомнит, почему именно этот список.
const WATCH: &[(&str, &str)] = &[
    // 🖥️ Конфигурация системы. Самое важное для отката: сетевые настройки,
    //    sudoers, systemd-юниты, fstab. Меняется редко, весит 14 МБ.
    ("etc", "/etc"),

    // 👤 Данные и настройки пользователя: конфиги, документы, проекты.
    ("home", "/home/pcadm"),

    // 📦 Состояние пакетного менеджера. Без него откатить удалённый
    //    пакет нельзя — только поставить обратно вручную.
    ("pacman", "/var/lib/pacman"),
];

/// 🚫 Что исключить из снимка: экономия места и «не грузить систему».
///
/// 📗 ГЛАВНОЕ ПРАВИЛО rsync, которое стоило мне первого снимка:
///     паттерны сравниваются НЕ с абсолютным путём, а с путём ОТНОСИТЕЛЬНО
///     корня передачи. При `rsync /home/pcadm/ dst` корень передачи — это
///     `/home/pcadm/`, поэтому путь `.snapshots` внутри передачи выглядит
///     как `/.snapshots`.
///     Паттерн `/home/pcadm/.snapshots` НЕ СРАБОТАЕТ: ведущий слэш в rsync
///     означает «якорь на корень передачи», то есть он ждёт путь
///     `/home/pcadm/.snapshots` ОТНОСИТЕЛЬНО `/home/pcadm/` — то есть
///     `/home/pcadm/home/pcadm/.snapshots`. Совпадения нет.
///     Итог: снимок копировал сам себя в себя.
///
///     Поэтому все паттерны ниже записаны относительными. Паттерн БЕЗ
///     ведущего слэша и с завершающим слэшем («имя/») означает «каталог с
///     таким именем на любой глубине» — это ровно то, что нужно.
const EXCLUDES: &[&str] = &[
    // 🚨 ХРАНИЛИЩЕ САМИХ СНИМКОВ. Живёт внутри /home/pcadm, который снимаем.
    //    Без этой строки — рекурсия и через несколько часов забитый диск.
    ".snapshots/",

    // 💾 Кэши: пересоздаются сами, между часами не меняются, весят сотни МБ.
    ".cache/",
    "tool-output/",

    // ⚙️ Тулчейн Rust: 640 МБ, восстанавливается одной командой rustup.
    ".rustup/",
    ".cargo/",

    // 🗑️ Корзина и временные файлы: там может быть что угодно и много.
    "Trash/",

    // 🔒 Привилегированные каталоги /etc: пользователь их физически не
    //    читает, rsync сыпет «Permission denied» и в лог, и в журнал
    //    каждый час. Смысла копировать то, что нельзя прочитать, нет —
    //    эти файлы восстанавливаются из пакета или из своего бэкапа.
    "/ssl/private/", "/sudoers.d/", "/shadow", "/gshadow",

    // 🧩 Служебные файлы ядра: восстанавливаются при загрузке.
    "/mtab", "/resolv.conf",
];

/// 🕐 Сколько снимков хранить. 24 = сутки истории почасовых откатов.
const KEEP_SNAPSHOTS: usize = 24;

/// 🚦 Минимальный запас свободного места. Ниже — снимок пропускается,
///    чтобы не забить систему до состояния, из которого не выбраться.
const MIN_FREE_MB: u64 = 2_000;

/// 🔒 Имя lock-файла, защищающего от параллельных запусков.
const LOCK_FILE: &str = "/tmp/sys-snapshot.lock";

