/// 📁 Корневой каталог снимков. Создаём сразу — иначе первый запуск упадёт.
fn snapshot_root() -> PathBuf {
    PathBuf::from(SNAPSHOT_ROOT)
}

/// 🆔 Метка снимка: время в UTC в формате 20261007-223045.
/// 📗 UTC, а не локальное время: перевод часов не должен ломать порядок
///    снимков и переносить их в будущее относительно прошлых.
fn snapshot_id() -> String {
    let secs = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    // 📌 Форматируем время вручную через civil-from-days: не тащим крейт
    //    ради двух строк даты, и это работает без внешних зависимостей.
    let days = (secs / 86_400) as i64;
    let tod = secs % 86_400;
    let (y, m, d) = civil_from_days(days);
    format!(
        "{y:04}{m:02}{d:02}-{:02}{:02}{:02}",
        tod / 3600,
        (tod % 3600) / 60,
        tod % 60
    )
}

/// 📆 Перевод дней с начала эпохи в дату (алгоритм Howard Hinnant).
/// Работает для любой даты, включая отрицательные дни — то есть надёжнее,
/// чем приблизительные «делим на 30».
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = (z - era * 146_097) as u64;                        // день внутри эры
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146_096) / 365;
    let y = yoe as i64 + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);           // день внутри года
    let mp = (5 * doy + 2) / 153;                                // месяц в схеме 0..11
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;               // день месяца
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;        // приводим к 1..12
    (if m <= 2 { y + 1 } else { y }, m, d)
}

/// 💾 Свободное место на разделе в мегабайтах.
fn free_mb(path: &str) -> u64 {
    // 📗 df -BM даёт целые мегабайты: нам нужна грубая оценка, точность
    //    до килобайта тут не имеет смысла.
    let out = Command::new("df").arg("-BM").arg(path).output();
    match out {
        Ok(o) if o.status.success() => {
            let text = String::from_utf8_lossy(&o.stdout);
            // 📌 df печатает заголовок + строку. Берём последнюю строку,
            //    колонка 4 — Available.
            text.lines()
                .nth(1)
                .and_then(|l| l.split_whitespace().nth(3))
                .and_then(|v| v.trim_end_matches('M').parse::<u64>().ok())
                .unwrap_or(0)
        }
        _ => 0,
    }
}

/// 🔒 Взять lock. `false` — другой процесс уже снимает.
fn acquire_lock() -> bool {
    // 📗 O_EXCL-создание атомарно: если файл уже есть — значит, кто-то
    //    занял его раньше. Так делается без гонок.
    fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(LOCK_FILE)
        .is_ok()
}

/// 🔓 Отпустить lock.
fn release_lock() {
    let _ = fs::remove_file(LOCK_FILE);
}

/// 📋 Снимки по возрастанию времени (старые слева).
fn list_snapshots() -> Vec<(String, PathBuf)> {
    let root = snapshot_root();
    let mut out: Vec<(String, PathBuf)> = Vec::new();

    // 📌 Каталог мог не быть создан — это не ошибка, просто снимков нет.
    let entries = match fs::read_dir(&root) {
        Ok(e) => e,
        Err(_) => return out,
    };

    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_dir() {
            continue;
        }
        if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
            out.push((name.to_string(), path));
        }
    }

    // 📗 Имена — метки времени фиксированной длины, поэтому лексикографически
    //    они совпадают с хронологическим порядком. Сортируем по имени.
    out.sort_by(|a, b| a.0.cmp(&b.0));
    out
}

