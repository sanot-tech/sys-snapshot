/// 📛 Стадия в квадратных скобках.
fn step(stage: &str, msg: &str) {
    println!("\x1b[36m[{stage}]\x1b[0m {msg}");
}

/// ✅ Успех.
fn ok(msg: &str) {
    println!("\x1b[32m  ✔\x1b[0m {msg}");
}

/// ❌ Ошибка.
fn err(msg: &str) {
    println!("\x1b[31m  ✘\x1b[0m {msg}");
}

/// 💬 Реплика без стадии.
fn info(msg: &str) {
    println!("{msg}");
}

