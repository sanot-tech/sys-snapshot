// 📋 ПОКАЗАТЬ СНИМКИ
// ===========================================================================

fn show_list() -> i32 {
    let all = list_snapshots();
    if all.is_empty() {
        info("Снимков пока нет. Запусти: sys-snapshot");
        return 0;
    }

    info(&format!("Всего снимков: {} (храним последние {KEEP_SNAPSHOTS})\n", all.len()));

    // 📗 Считаем место ОДИН раз по всему хранилищу, а не по каждому
    //    снимку отдельно: du не дедуплицирует хардлинки между аргументами,
    //    поэтому сумма по снимкам считала бы одни и те же файлы дважды.
    let total = Command::new("du")
        .arg("-smc")
        .arg(SNAPSHOT_ROOT)
        .output()
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .and_then(|t| t.lines().next_back()?.split_whitespace().next().map(|s| s.to_string()))
        .unwrap_or_else(|| "?".into());
    info(&format!("  ЗАНЯТО ВСЕГО: {total} МБ  (учитывает общие файлы один раз)\n"));

    // 📌 Список снимков — новые сверху.
    for (name, path) in all.iter().rev() {
        info(&format!("  {name}   {}", path.display()));
    }
    info("\nОткат: sys-snapshot --restore <ID>");
    0
}

// ===========================================================================
// ⏪ ОТКАТ
// ----------------------------------------------------------------------------
// ВАЖНО: инструмент НЕ делает откат сам и не просит root. Он печатает
// точные команды с реальными путями. Причина: автоматический откат /etc
// вслепую — это способ угробить систему, если снимок оказался плохим.
// Решение принимает человек, у которого перед глазами команды.
// ===========================================================================

fn show_restore(id: &str) -> i32 {
    let all = list_snapshots();
    let found = all.iter().find(|(n, _)| n == id);

    let (_, path) = match found {
        Some(f) => f,
        None => {
            err(&format!("снимок {id} не найден"));
            info("   Доступные: sys-snapshot --list");
            return 1;
        }
    };

    info(&format!("\x1b[1;33m⏪ Откат к снимку {id}\x1b[0m — {}\n", path.display()));
    info("Ничего не применяется автоматически. Сначала посмотри, потом решай.");

    info("\n\x1b[1m# 1. Посмотреть, что вообще в снимке:\x1b[0m");
    info(&format!("ls -la {}/etc {}/home", path.display(), path.display()));

    info("\n\x1b[1m# 2. СПЕРВА сделать копию текущего состояния (чтобы откат был обратим):\x1b[0m");
    // 📗 Раньше здесь стоял путь ВНУТРИ снимка. Это плохо по двум причинам:
    //    1) мы бы писали в снимок, который сам потом используем как точку
    //       отката, то есть портили бы единственный ориентир;
    //    2) каталог снимка принадлежит пользователю, а запись туда шла бы
    //       от root — лишние права без нужды.
    //    Отдельный каталог в /tmp — он одноразовый и точно не перепутается.
    info("sudo mkdir -p /tmp/pre-rollback && sudo rsync -a --fake-super /etc/ /tmp/pre-rollback/etc/");

    info("\n\x1b[1m# 3. Откатить ОДИН файл (безопасно, начни с этого):\x1b[0m");
    info(&format!("sudo rsync -a --super {}/etc/fstab /etc/fstab", path.display()));

    info("\n\x1b[1m# 4. Откатить каталог целиком (перезапишет текущее содержимое):\x1b[0m");
    // 📗 Флаг --super ОБЯЗАТЕЛЕН. Мы снимали снимок с --fake-super: владелец
    //    лежит в расширенном атрибуте user.rootless.*, а на диске файл
    //    принадлежит пользователю. Обычный `rsync -a` этот атрибут не
    //    прочитает и восстановит файлы с владельцем pcadm — а в /etc
    //    это ломает систему. Именно --super заставляет rsync под root
    //    достать и применить сохранённого владельца.
    info(&format!("sudo rsync -a --super {}/etc/ /etc/", path.display()));
    info(&format!("sudo rsync -a --super {}/home/ /home/", path.display()));

    info("\n\x1b[1m# 5. Перезагрузиться, если менял systemd:\x1b[0m");
    info("sudo systemctl daemon-reload && sudo reboot");

    info("\n\x1b[33m⚠️  Пункт 4 перезапишет всё, что менялось ПОСЛЕ снимка.\x1b[0m");
    info("\x1b[32m↩ Откатить откат: sudo rsync -a /tmp/pre-rollback/etc/ /etc/\x1b[0m");
    0
}

// ===========================================================================
// 🏁 MAIN
// ===========================================================================

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();

    info("\x1b[1;35m📸  sys-snapshot\x1b[0m — почасовые снапшоты с откатом (Rust)");
    info(&format!("   хранилище: {SNAPSHOT_ROOT}   храним последних: {KEEP_SNAPSHOTS}"));

    // 📂 Каталог хранилища нужен почти для всех режимов.
    if fs::create_dir_all(snapshot_root()).is_err() {
        err("не удалось создать каталог хранилища");
        std::process::exit(1);
    }

    // 🔒 Блокировка от параллельных запусков: без неё два снимка в один
    //    час будут писать в один каталог и портить друг другу ссылки.
    if !acquire_lock() {
        err("другой снимок уже снимается — подожди");
        std::process::exit(1);
    }

    // 🧹 Гарантированно снимаем lock при выходе, даже при ошибке.
    let code = match args.first().map(|s| s.as_str()) {
        Some("--list") => show_list(),
        Some("--restore") => match args.get(1) {
            Some(id) => show_restore(id),
            None => {
                err("нужен ID снимка: sys-snapshot --restore 20261007-223045");
                1
            }
        },
        Some(other) => {
            err(&format!("неизвестный аргумент: {other}"));
            info("   sys-snapshot | --list | --restore <ID>");
            1
        }
        // 📸 По умолчанию — снять снимок.
        None => take_snapshot(),
    };

    release_lock();
    std::process::exit(code);
}